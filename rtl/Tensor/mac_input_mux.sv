// ============================================================================
// MAC Input Multiplexer v4.3 (Round E1 / R2.1)
// ============================================================================
//
// Pure combinational block that demultiplexes the 16-bit packed weight and
// activation operands into mode-specific sub-fields for three consumers:
//
//   1. mul_a[4], mul_b[4]  → 4× UINT4 fracturable multiplier array
//      Used by: UINT4_SIMD (direct), UINT8/MXINT8/BF16 (cross-product)
//
//   2. fp4_a[4], fp4_b[4]  → mac_lru FP4 lane inputs
//      Used by: MODE_FP4, MODE_MXFP4
//
//   3. fp8_a[2], fp8_b[2]  → mac_lru FP8 lane inputs
//      Used by: MODE_FP8, MODE_MXFP8
//
//   4. fp_sign/exp/mant    → BF16 direct exponent/sign path
//      Used by: MODE_BF16 (bypasses LRU, feeds FP accumulator directly)
//
// Previously named upe_input_mux. Renamed as part of the Round E naming
// cleanup (UPE → MAC cell distinction). No functional changes.
//
// ----------------------------------------------------------------------------
// Round E1 / R2.1 changes:
//   - File  rename: upe_input_mux.sv → mac_input_mux.sv
//   - Module rename: upe_input_mux  → mac_input_mux
//   - Package import: upe_pkg → tensor_pkg
//   - Type rename:    upe_mode_e → tensor_mode_e
//   - Comment updates: "upe_lru" → "mac_lru"
//   - No functional logic changes
//
// ----------------------------------------------------------------------------
// Fracturable multiplier mapping for 8-bit modes (UINT8/BF16/MXINT8):
//   The 4× UINT4 multipliers compute cross-products of two 8-bit values
//   split into high/low nibbles. The downstream adder tree recombines:
//
//     w[7:0] × a[7:0] = mul[0]           (w_lo × a_lo)
//                      + (mul[1]+mul[2])<<4  (cross terms)
//                      + mul[3]<<8        (w_hi × a_hi)
//
//     mul_a[0]=w[3:0]  mul_b[0]=a[3:0]   // LL
//     mul_a[1]=w[7:4]  mul_b[1]=a[3:0]   // HL
//     mul_a[2]=w[3:0]  mul_b[2]=a[7:4]   // LH
//     mul_a[3]=w[7:4]  mul_b[3]=a[7:4]   // HH
//
// v4.2 changes:
//
//   A4 FIX — lane_valid[3:0] tail mask gating:
//     New input `lane_valid` gates each output lane. Invalid lanes (where
//     lane_valid[i]=0) have their outputs forced to zero. This enforces
//     tail mask semantics on the last K group when K % pack_factor != 0.
//     The lane_valid signal is generated by the tile controller and
//     propagated through MAC cell → input_mux.
//
//   A2/ARCH — 2:4 PE-internal activation selection REMOVED:
//     In v4.1, the input_mux contained metadata-guided activation candidate
//     selection logic (sparse_2_4_en, sparse_meta, candidate arrays).
//     In v4.2, structured sparse element selection is performed by the
//     Vector Unit BEFORE fragment formation. The MAC cell receives
//     Tensor-native 16b fragments that are identical in format to dense
//     fragments. Therefore, all 2:4-related logic has been removed:
//       - Removed: sparse_2_4_en input
//       - Removed: sparse_meta input
//       - Removed: act_fp4_candidates / act_fp8_candidates arrays
//       - Removed: all `if (sparse_2_4_en)` branches
//
// v4.0 changes:
//   - FP4 4-lane / FP8 2-lane split outputs added (v3.0 had none)
//   - FP4/FP8/MX modes drive mul_a/b to zero (LRU handles multiply internally)
//   - BF16 decomposition extracts {sign, exp[7:0], {1'b1,frac[6:0]}} explicitly
//
// Author:  H-Tensor Project
// Version: 4.3 (Round E1 / R2.1 — tensor_pkg migration)
// ============================================================================

module mac_input_mux
  import tensor_pkg::*;
(
  // ---- Packed Operand Inputs ----
  input  logic [15:0]  weight_active,  // 16-bit weight (from weight register)
  input  logic [15:0]  act_in,         // 16-bit activation (from data bus)
  input  tensor_mode_e mode,

  // ---- Lane Valid Mask (v4.2 — tail mask from controller) ----
  //
  // Per-lane active mask. lane_valid[i]=1 means lane i has valid data.
  // lane_valid[i]=0 forces lane i outputs to zero (power gating + correctness).
  //
  // In non-tail cycles:  lane_valid = mode_full_lane_mask(mode)
  // In last K cycle:     lane_valid has some bits cleared per K remainder
  // Outside COMPUTE:     lane_valid = 4'b0000
  //
  // Lane mapping:
  //   FP4/MXFP4/UINT4_SIMD: lane 0..3 → 4 independent elements
  //   FP8/MXFP8:            lane 0..1 → 2 independent elements (2..3 always 0)
  //   BF16/UINT8/MXINT8:    lane 0    → 1 element (1..3 always 0)
  input  logic [3:0]   lane_valid,

  // ---- 4× UINT4 Fracturable Multiplier Inputs ----
  output logic [3:0]   mul_a [4],      // Multiplier A operands (4 lanes)
  output logic [3:0]   mul_b [4],      // Multiplier B operands (4 lanes)

  // ---- LRU FP4 Inputs (4 lanes) ----
  output logic [3:0]   fp4_a [4],
  output logic [3:0]   fp4_b [4],

  // ---- LRU FP8 Inputs (2 lanes) ----
  output logic [7:0]   fp8_a [2],
  output logic [7:0]   fp8_b [2],

  // ---- BF16 Decomposed Fields ----
  output logic         fp_sign_a,
  output logic         fp_sign_b,
  output logic [7:0]   fp_exp_a,
  output logic [7:0]   fp_exp_b,
  output logic [7:0]   fp_mant_a,
  output logic [7:0]   fp_mant_b
);

  // ==========================================================================
  // Internal: 8-bit operand nibble aliases (for fracturable modes)
  // ==========================================================================
  logic [3:0] w_lo, w_hi, a_lo, a_hi;

  // v4.1 (R4): MXINT8 sign separation — unsigned magnitudes for multiplier
  logic [7:0] mxint_mag_a, mxint_mag_b;

  always_comb begin
    w_lo = weight_active[3:0];
    w_hi = weight_active[7:4];
    a_lo = act_in[3:0];
    a_hi = act_in[7:4];

    // MXINT8: abs(INT8) — 2's complement → unsigned magnitude
    //   -128 (8'h80) → 128 (8'h80): safe, fits in 8-bit unsigned [0,128]
    mxint_mag_a = weight_active[7] ? (8'd0 - weight_active[7:0]) : weight_active[7:0];
    mxint_mag_b = act_in[7]        ? (8'd0 - act_in[7:0])        : act_in[7:0];
  end

  // ==========================================================================
  // Main Demux Logic
  // ==========================================================================
  always_comb begin

    // Default: all outputs inactive / zero
    for (int i = 0; i < 4; i++) begin
      mul_a[i] = 4'd0;
      mul_b[i] = 4'd0;
      fp4_a[i] = 4'd0;
      fp4_b[i] = 4'd0;
    end
    for (int i = 0; i < 2; i++) begin
      fp8_a[i] = 8'd0;
      fp8_b[i] = 8'd0;
    end
    fp_sign_a = 1'b0;
    fp_sign_b = 1'b0;
    fp_exp_a  = 8'd0;
    fp_exp_b  = 8'd0;
    fp_mant_a = 8'd0;
    fp_mant_b = 8'd0;

    unique case (mode)

      // -----------------------------------------------------------------
      // UINT4 SIMD — 4 independent 4×4 multiplies
      // -----------------------------------------------------------------
      MODE_UINT4_SIMD: begin
        mul_a[0] = weight_active[3:0];   mul_b[0] = act_in[3:0];
        mul_a[1] = weight_active[7:4];   mul_b[1] = act_in[7:4];
        mul_a[2] = weight_active[11:8];  mul_b[2] = act_in[11:8];
        mul_a[3] = weight_active[15:12]; mul_b[3] = act_in[15:12];

        // v4.2: lane_valid gating — invalid lanes forced to zero
        for (int i = 0; i < 4; i++) begin
          if (!lane_valid[i]) begin
            mul_a[i] = 4'd0;
            mul_b[i] = 4'd0;
          end
        end
      end

      // -----------------------------------------------------------------
      // UINT8 — single 8×8 via fracturable tree
      // -----------------------------------------------------------------
      MODE_UINT8: begin
        mul_a[0] = w_lo;   mul_b[0] = a_lo;
        mul_a[1] = w_hi;   mul_b[1] = a_lo;
        mul_a[2] = w_lo;   mul_b[2] = a_hi;
        mul_a[3] = w_hi;   mul_b[3] = a_hi;

        // v4.2: lane_valid[0] gates the entire fracturable multiply
        // (All 4 partial products contribute to a single 8×8 result,
        //  so if lane 0 is invalid, all must be gated.)
        if (!lane_valid[0]) begin
          for (int i = 0; i < 4; i++) begin
            mul_a[i] = 4'd0;
            mul_b[i] = 4'd0;
          end
        end
      end

      // -----------------------------------------------------------------
      // MXINT8 — sign separation + fracturable tree
      // -----------------------------------------------------------------
      MODE_MXINT8: begin
        fp_sign_a = weight_active[7];
        fp_sign_b = act_in[7];
        mul_a[0] = mxint_mag_a[3:0];  mul_b[0] = mxint_mag_b[3:0];
        mul_a[1] = mxint_mag_a[7:4];  mul_b[1] = mxint_mag_b[3:0];
        mul_a[2] = mxint_mag_a[3:0];  mul_b[2] = mxint_mag_b[7:4];
        mul_a[3] = mxint_mag_a[7:4];  mul_b[3] = mxint_mag_b[7:4];

        // v4.2: lane_valid[0] gates the entire fracturable multiply
        if (!lane_valid[0]) begin
          fp_sign_a = 1'b0;
          fp_sign_b = 1'b0;
          for (int i = 0; i < 4; i++) begin
            mul_a[i] = 4'd0;
            mul_b[i] = 4'd0;
          end
        end
      end

      // -----------------------------------------------------------------
      // BF16 — decompose + fracturable tree
      // -----------------------------------------------------------------
      MODE_BF16: begin
        fp_sign_a = weight_active[15];
        fp_sign_b = act_in[15];
        fp_exp_a  = weight_active[14:7];
        fp_exp_b  = act_in[14:7];
        fp_mant_a = {1'b1, weight_active[6:0]};
        fp_mant_b = {1'b1, act_in[6:0]};
        mul_a[0] = fp_mant_a[3:0];  mul_b[0] = fp_mant_b[3:0];
        mul_a[1] = fp_mant_a[7:4];  mul_b[1] = fp_mant_b[3:0];
        mul_a[2] = fp_mant_a[3:0];  mul_b[2] = fp_mant_b[7:4];
        mul_a[3] = fp_mant_a[7:4];  mul_b[3] = fp_mant_b[7:4];

        // v4.2: lane_valid[0] gates the entire BF16 multiply path
        if (!lane_valid[0]) begin
          fp_sign_a = 1'b0;
          fp_sign_b = 1'b0;
          fp_exp_a  = 8'd0;
          fp_exp_b  = 8'd0;
          fp_mant_a = 8'd0;
          fp_mant_b = 8'd0;
          for (int i = 0; i < 4; i++) begin
            mul_a[i] = 4'd0;
            mul_b[i] = 4'd0;
          end
        end
      end

      // -----------------------------------------------------------------
      // FP4 / MXFP4 — 4 parallel FP4 lanes via LRU
      // -----------------------------------------------------------------
      //
      // v4.2: 2:4 activation selection logic REMOVED.
      // In v4.1, this branch contained an `if (sparse_2_4_en)` sub-path
      // that used sparse_meta to select from act_fp4_candidates.
      // In v4.2, structured sparse selection is performed by Vector Unit
      // before fragment formation. MAC cell receives pre-selected fragments.
      MODE_FP4, MODE_MXFP4: begin
        fp4_a[0] = weight_active[3:0];   fp4_b[0] = act_in[3:0];
        fp4_a[1] = weight_active[7:4];   fp4_b[1] = act_in[7:4];
        fp4_a[2] = weight_active[11:8];  fp4_b[2] = act_in[11:8];
        fp4_a[3] = weight_active[15:12]; fp4_b[3] = act_in[15:12];

        // v4.2: lane_valid gating — invalid lanes forced to zero
        for (int i = 0; i < 4; i++) begin
          if (!lane_valid[i]) begin
            fp4_a[i] = 4'd0;
            fp4_b[i] = 4'd0;
          end
        end
      end

      // -----------------------------------------------------------------
      // FP8 / MXFP8 — 2 parallel FP8 lanes via LRU
      // -----------------------------------------------------------------
      //
      // v4.2: 2:4 activation selection logic REMOVED (same rationale as FP4).
      MODE_FP8, MODE_MXFP8: begin
        fp8_a[0] = weight_active[7:0];   fp8_b[0] = act_in[7:0];
        fp8_a[1] = weight_active[15:8];  fp8_b[1] = act_in[15:8];

        // v4.2: lane_valid gating — invalid lanes forced to zero
        for (int i = 0; i < 2; i++) begin
          if (!lane_valid[i]) begin
            fp8_a[i] = 8'd0;
            fp8_b[i] = 8'd0;
          end
        end
      end

      default: ;

    endcase
  end

endmodule
